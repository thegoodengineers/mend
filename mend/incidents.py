"""neatlogs found it, Mend fixed it: check every incident neatlogs' triage raised on our agent against the run files.

    python -m mend.incidents       # -> evidence/neatlogs-incidents.json and evidence/neatlogs-incidents.md

neatlogs auto-triages incidents from our traces and detections (triage_list / triage_get over its MCP server):
a root cause, the traces behind it, and a recommended action with verification steps. For each incident this
maps every linked trace to the run file and worker version it came from, then applies neatlogs' own check
(the turn threshold in its verification steps) to the original worker's runs and to fresh runs of the
current worker in runs/incident/. Read-only: resolving the card in neatlogs needs a person (see the .md).
"""

import asyncio
import json
import re
import sys
from pathlib import Path

from mend.tasks import ROOT
from mend.traces import _call

RUNS = ROOT / "runs"
OUT = ROOT / "evidence" / "neatlogs-incidents"
SLOW = 6  # turns; the threshold of Mend's own "slow solve (6+ turns)" detection


def run_files() -> list[dict]:
    out = []
    for p in sorted(RUNS.glob("**/*.json")):
        if p.name.count(".") != 1 or "invalid" in p.parts:
            continue
        r = json.loads(p.read_text(encoding="utf-8"))
        if isinstance(r, dict) and "tasks" in r and r.get("agent") != "analyst":
            out.append({**r, "file": str(p.relative_to(ROOT)).replace("\\", "/")})
    return out


def mean(xs: list[float]) -> float | None:
    return round(sum(xs) / len(xs), 2) if xs else None


def check(card: dict, runs: list[dict]) -> dict:
    by_trace = {t["trace_id"]: (r, t) for r in runs for t in r["tasks"] if t.get("trace_id")}
    linked = [{"trace_id": tid, "run": r["file"], "worker": r["worker_commit"], "task": t["task_id"], "turns": t.get("turns"),
               "passed": t["passed"]} for tid in card["linked_trace_ids"] if tid in by_trace for r, t in [by_trace[tid]]]
    tasks = sorted({x["task"] for x in linked})
    flagged = {x["worker"] for x in linked if (x["turns"] or 0) >= SLOW}
    m = re.search(r"below (\d+)", " ".join(card.get("recommended_action", {}).get("verification", [])))
    limit = int(m.group(1)) if m else SLOW

    original = [r for r in runs if r["worker_commit"] in flagged and any(t.get("trace_id") in card["linked_trace_ids"] for t in r["tasks"])]
    fresh = [r for r in runs if r["file"].startswith("runs/incident/")]
    covered = {t["task_id"] for r in fresh for t in r["tasks"]}
    compared = [t for t in tasks if t in covered] if fresh else tasks  # the tasks both sides ran

    def side(rs: list[dict]) -> dict:
        rs = [r for r in rs if any(t["task_id"] in compared for t in r["tasks"])]
        ts = [t for r in rs for t in r["tasks"] if t["task_id"] in compared]
        turns = [t["turns"] for t in ts if t.get("turns")]
        return {"runs": [r["file"] for r in rs], "tasks": len(ts), "passed": sum(t["passed"] for t in ts),
                "mean_turns": mean(turns), "slow_share": mean([float(x >= SLOW) for x in turns]),
                "meets_check": mean(turns) is not None and mean(turns) < limit}
    return {"triage_id": card["triage_id"], "title": card["title"], "severity": card["severity"], "status": card["status"],
            "workflow": card.get("workflow_name"), "created_at": card["created_at"], "root_cause": card["root_cause"],
            "recommended_action": card.get("recommended_action", {}), "linked": linked, "tasks": compared,
            "check": f"mean turns on the linked tasks below {limit}", "original": side(original), "current": side(fresh)}


def report(results: list[dict]) -> str:
    lines = ["# Incidents neatlogs raised on our agent, checked against the run files", "",
             "Generated by `python -m mend.incidents` from neatlogs' triage (read over its MCP server) and `runs/`.", ""]
    for r in results:
        o, c = r["original"], r["current"]
        cause = re.sub(r"`?\{\{trace:([0-9a-f]+)\}\}`?", r"`\1`", r["root_cause"])
        lines += [f"## {r['title']}", "",
                  f"neatlogs triage `{r['triage_id']}` · {r['severity']} · {r['status']} · workflow `{r['workflow']}` · raised {r['created_at'][:16]} UTC", "",
                  f"**neatlogs' root cause:** {cause}", "",
                  "**Where its linked traces come from:**", "", "| Trace | Run file | Worker | Task | Turns | Passed |", "|---|---|---|---|---|---|"]
        lines += [f"| `{x['trace_id'][:12]}` | [{Path(x['run']).name}](../{x['run']}) | `{x['worker']}` | {x['task']} | {x['turns']} | {x['passed']} |"
                  for x in r["linked"]]
        lines += ["", f"**neatlogs' own verification step, applied** ({r['check']}; tasks {', '.join(r['tasks'])}):", "",
                  "| Worker | Runs | Tasks | Passed | Mean turns | Share with 6+ turns | Check |", "|---|---|---|---|---|---|---|",
                  f"| original (runs that triggered it) | {len(o['runs'])} | {o['tasks']} | {o['passed']} | {o['mean_turns']} | {o['slow_share']} | {'met' if o['meets_check'] else 'not met'} |",
                  f"| current, fresh runs (`runs/incident/`) | {len(c['runs'])} | {c['tasks']} | {c['passed']} | {c['mean_turns']} | {c['slow_share']} | {'met' if c['meets_check'] else 'not met'} |",
                  ""]
    return "\n".join(lines)


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    cards = asyncio.run(_call("triage_list", {})).get("triage_cards", [])
    runs = run_files()
    results = [check(asyncio.run(_call("triage_get", {"triage_id": c["triage_id"]})), runs) for c in cards]
    OUT.with_suffix(".json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    OUT.with_suffix(".md").write_text(report(results), encoding="utf-8")
    for r in results:
        print(f"{r['title']}: original mean turns {r['original']['mean_turns']}, current {r['current']['mean_turns']} ({r['check']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
